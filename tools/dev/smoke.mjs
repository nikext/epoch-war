// Dev: drive the real UI like a player and report errors.
import { chromium } from 'playwright-core';
import { readdirSync } from 'node:fs';
const root = process.env.HOME + '/.cache/ms-playwright';
const dir = readdirSync(root).find((d) => d.startsWith('chromium_headless_shell'));
const browser = await chromium.launch({ executablePath: `${root}/${dir}/chrome-headless-shell-linux64/chrome-headless-shell`, args: ['--use-angle=swiftshader', '--enable-unsafe-swiftshader'] });
const page = await browser.newPage({ viewport: { width: 1440, height: 810 } });
const errors = [];
page.on('pageerror', (e) => errors.push(`pageerror: ${e.message}`));
page.on('console', (m) => { if (m.type() === 'error') errors.push(`console: ${m.text()}`); });
const base = process.env.SHOOT_BASE ?? 'http://localhost:5180';
const state = () => page.evaluate(() => { const w = window.__game.world; const s = w.sides[0]; return { mode: window.__game.mode, paused: window.__game.paused, age: s.age, gold: Math.round(s.gold), queue: s.queue.length, units: w.units.filter((u) => u.side === 0).length, slots: s.slots, turrets: s.turrets.filter(Boolean).length, cd: Math.round(s.specialCd), draft: s.draft, doctrines: s.doctrines, winner: w.winner }; });
const log = async (label) => console.log(label.padEnd(26), JSON.stringify(await state()));

await page.goto(base + '/?quality=low', { waitUntil: 'load' });
await page.waitForSelector('.loading.done', { timeout: 20000 });
await page.click('[data-go="new"]');
await page.click('[data-d="recruit"]');
await page.waitForTimeout(800);
await log('war started');
await page.keyboard.press('Digit1');
await page.keyboard.press('Digit1');
await page.keyboard.press('Digit2');
await log('queued 3 via keys');
await page.click('.card >> nth=0');
await log('clicked first card');
await page.waitForTimeout(3000);
await log('after 3s');
await page.click('.slot.add');
await log('bought a ledge');
await page.click('.slot >> nth=2');
await page.waitForTimeout(300);
await page.screenshot({ path: 'shots/ui-turret-popover.png' });
await page.click('.popover .opt >> nth=0');
await log('built a turret');
await page.keyboard.press('KeyU');
await page.waitForTimeout(300);
await page.screenshot({ path: 'shots/ui-armory.png' });
await page.keyboard.press('Escape');
await page.evaluate(() => { window.__game.world.sides[0].specialCd = 0; });
await page.keyboard.press('Space');
await page.mouse.move(900, 600);
await page.waitForTimeout(200);
await page.screenshot({ path: 'shots/ui-aim.png' });
await page.mouse.click(900, 600);
await log('cast aimed special');
await page.keyboard.press('KeyP');
await page.waitForTimeout(400);
await page.screenshot({ path: 'shots/ui-pause.png' });
await log('paused');
await page.click('[data-go="resume"]');
await page.evaluate(() => { window.__game.world.sides[0].xp = 99999; });
await page.keyboard.press('KeyE');
await page.waitForTimeout(3200);
await log('evolved, draft open?');
await page.screenshot({ path: 'shots/ui-draft.png' });
await page.keyboard.press('Digit2');
await page.waitForTimeout(300);
await log('picked doctrine 2');
await page.keyboard.press('KeyF');
await page.keyboard.press('KeyH');
await log('speed + hold');
await page.evaluate(() => { const w = window.__game.world; w.sides[1].baseHp = 1; });
await page.keyboard.press('KeyH');
await page.evaluate(() => { const w = window.__game.world; const u = w.spawn(0, w.sides[0].age === 1 ? { ...w.units[0]?.def } : w.units[0].def); u.x = 99; });
await page.waitForTimeout(6000);
await log('enemy wall at 1hp');
await page.screenshot({ path: 'shots/ui-result.png' });
console.log(errors.length ? errors.join('\n') : 'no errors');
await browser.close();
